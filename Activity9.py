#Relational Operators

# > Greater tha
# < Less than
# >= Greater than or equal
# <= : Less than or equal
# == : Equal to
# != : Not equal to

# ----- All relational value returns a boolean (True or False) --------------------

# in numbers
print("------Relational Operators in Numbers------")

x = 10
y = 5


print(x<y) # false
print(x>y) # true
print(x<=y) # false
print(x<=y) #false
print(x==y) #false since 10 is not equal to 5

